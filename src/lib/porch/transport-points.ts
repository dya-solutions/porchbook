export function findRide(place: string) {
  const key = place.trim().toLowerCase();
  if (!key) return null;
  for (const ride of RIDES) {
    const stage = ride.stages.find((item) => item.toLowerCase() === key);
    if (stage) return { division: ride.division, stage };
  }
  return null;
}

export function rideNotice(place: string) {
  const ride = findRide(place);
  if (!ride) return "";
  return `${ride.stage}. Pickup at ${PICKUP_TIME}. Gates open at ${GATES_OPEN}.`;
}
